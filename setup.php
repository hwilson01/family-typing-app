<?php
// One-time setup. Creates api/config.php, builds the tables, seeds the
// curriculum, and creates the first parent profile.
//
// Run it one of two ways:
//   * Browser: visit  <your-site>/projects/typing/setup.php  and fill the form.
//   * Terminal (if you have SSH):  php setup.php
//
// DELETE this file afterwards. It refuses to run once config.php exists.
declare(strict_types=1);

require_once __DIR__ . '/api/lib/db.php';
require_once __DIR__ . '/api/lib/migrate.php';
require_once __DIR__ . '/api/lib/seed.php';

$CONFIG = __DIR__ . '/api/config.php';
$isCli = (php_sapi_name() === 'cli');

function done_message(array $res, bool $cli): void {
    $msg = "Setup complete.\n"
         . "  Lessons seeded: {$res['total']}\n"
         . "  Parent profile created: {$res['parent']}\n\n"
         . "IMPORTANT: delete setup.php now.\n";
    if ($cli) { echo $msg; }
    else {
        echo '<!doctype html><meta charset="utf-8"><title>Setup complete</title>'
           . '<style>body{font:18px/1.5 system-ui;margin:3rem auto;max-width:34rem}'
           . 'code{background:#eee;padding:.1em .3em;border-radius:4px}</style>'
           . '<h1>All set</h1><p>Lessons seeded: <b>' . (int)$res['total'] . '</b></p>'
           . '<p>Parent profile: <b>' . htmlspecialchars($res['parent']) . '</b></p>'
           . '<p style="color:#b00"><b>Now delete <code>setup.php</code> from the server.</b></p>'
           . '<p><a href="index.html">Open the app &rarr;</a></p>';
    }
}

function run_setup(array $in, string $configPath): array {
    // Build config array
    $cfg = [
        'db_driver' => $in['db_driver'] ?: 'mysql',
        'db_host'   => $in['db_host'] ?: '127.0.0.1',
        'db_port'   => (int)($in['db_port'] ?: 3306),
        'db_name'   => $in['db_name'],
        'db_user'   => $in['db_user'],
        'db_pass'   => $in['db_pass'],
        'db_path'   => __DIR__ . '/db/local.sqlite',
        'family_password_hash' => password_hash($in['family_password'], PASSWORD_DEFAULT),
        'anthropic_api_key' => '',
        'ai_month_cap' => 200,
        'pin_max_attempts' => 5,
        'pin_lockout_minutes' => 15,
    ];

    DB::init($cfg);
    migrate();
    $seed = seed_curriculum();

    // Create the first parent profile if none exists.
    $existing = DB::one("SELECT id FROM profiles WHERE role = 'parent' LIMIT 1");
    if (!$existing) {
        DB::insert('INSERT INTO profiles (name, avatar, role, pin_hash, current_lesson, reading_level, created_at)
                    VALUES (?,?,?,?,?,?,?)',
            [$in['parent_name'], $in['parent_avatar'] ?: 'owl', 'parent',
             password_hash($in['parent_pin'], PASSWORD_DEFAULT), 1, 6, DB::now()]);
    }

    // Write config.php last, so a failure above doesn't lock setup out.
    $export = "<?php\n// Generated by setup.php on " . gmdate('Y-m-d H:i:s') . " UTC.\nreturn "
            . var_export($cfg, true) . ";\n";
    file_put_contents($configPath, $export);

    return ['total' => $seed['total'], 'parent' => $in['parent_name']];
}

function validate(array $in): array {
    $errs = [];
    if (($in['db_driver'] ?: 'mysql') === 'mysql') {
        foreach (['db_name', 'db_user'] as $k) {
            if (trim((string)$in[$k]) === '') $errs[] = "Database $k is required.";
        }
    }
    if (strlen((string)$in['family_password']) < 6) $errs[] = 'Family password needs at least 6 characters.';
    if (trim((string)$in['parent_name']) === '') $errs[] = 'Parent name is required.';
    if (!preg_match('/^\d{6,10}$/', (string)$in['parent_pin'])) $errs[] = 'Parent PIN must be 6 to 10 digits.';
    return $errs;
}

// ---------------- CLI ----------------
if ($isCli) {
    if (file_exists($CONFIG)) {
        fwrite(STDERR, "api/config.php already exists. Delete it first to re-run setup.\n");
        exit(1);
    }
    $prompt = function ($label, $hidden = false) {
        echo $label;
        if ($hidden && function_exists('shell_exec')) {
            system('stty -echo'); $v = rtrim(fgets(STDIN), "\n"); system('stty echo'); echo "\n";
            return $v;
        }
        return rtrim(fgets(STDIN), "\n");
    };
    $in = [
        'db_driver' => $prompt('DB driver [mysql]: ') ?: 'mysql',
        'db_host'   => $prompt('DB host [127.0.0.1]: ') ?: '127.0.0.1',
        'db_port'   => $prompt('DB port [3306]: ') ?: '3306',
        'db_name'   => $prompt('DB name: '),
        'db_user'   => $prompt('DB user: '),
        'db_pass'   => $prompt('DB password: ', true),
        'family_password' => $prompt('Family password (shared, 6+ chars): ', true),
        'parent_name'   => $prompt('First parent name: '),
        'parent_avatar' => $prompt('Parent avatar [owl]: ') ?: 'owl',
        'parent_pin'    => $prompt('Parent PIN (6-10 digits): ', true),
    ];
    $errs = validate($in);
    if ($errs) { fwrite(STDERR, "- " . implode("\n- ", $errs) . "\n"); exit(1); }
    try {
        $res = run_setup($in, $CONFIG);
        done_message($res, true);
    } catch (Throwable $e) {
        fwrite(STDERR, 'Setup failed: ' . $e->getMessage() . "\n"); exit(1);
    }
    exit(0);
}

// ---------------- Web ----------------
if (file_exists($CONFIG)) {
    http_response_code(409);
    echo '<!doctype html><meta charset="utf-8"><p style="font:18px system-ui;margin:3rem">'
       . 'Setup has already run (<code>api/config.php</code> exists). '
       . 'Delete <code>setup.php</code>. To start over, remove <code>api/config.php</code> first.</p>';
    exit;
}

$errors = [];
if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    $in = array_map(fn($k) => $_POST[$k] ?? '', array_flip([
        'db_driver','db_host','db_port','db_name','db_user','db_pass',
        'family_password','parent_name','parent_avatar','parent_pin',
    ]));
    // array_flip gives values as keys; rebuild cleanly:
    $in = [
        'db_driver' => $_POST['db_driver'] ?? 'mysql',
        'db_host' => $_POST['db_host'] ?? '127.0.0.1',
        'db_port' => $_POST['db_port'] ?? '3306',
        'db_name' => $_POST['db_name'] ?? '',
        'db_user' => $_POST['db_user'] ?? '',
        'db_pass' => $_POST['db_pass'] ?? '',
        'family_password' => $_POST['family_password'] ?? '',
        'parent_name' => $_POST['parent_name'] ?? '',
        'parent_avatar' => $_POST['parent_avatar'] ?? 'owl',
        'parent_pin' => $_POST['parent_pin'] ?? '',
    ];
    $errors = validate($in);
    if (!$errors) {
        try { done_message(run_setup($in, $CONFIG), false); exit; }
        catch (Throwable $e) { $errors[] = 'Setup failed: ' . $e->getMessage(); }
    }
}
